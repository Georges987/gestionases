<?php
/**
 * Migration SQLite → PostgreSQL — Gestion ONG
 *
 * Lit les bases SQLite sources (users.db, gestion.db) et recopie tout dans
 * PostgreSQL (structure déjà créée par api/db.php via PDO).
 *
 * Usage :
 *   php tools/migrate_sqlite_to_postgres.php \
 *       --users=./api/data/users.db \
 *       --gestion=./api/data/gestion.db \
 *       --host=localhost --port=5432 --dbname=gestion_ong \
 *       --user=gestion --password=secret [--sslmode=require] [--dry-run]
 *
 * Équivalent via variables d'environnement :
 *   DB_DRIVER=postgres DB_HOST=... DB_NAME=... DB_USER=... DB_PASSWORD=... \
 *   SQLITE_USERS_DB=./api/data/users.db SQLITE_GESTION_DB=./api/data/gestion.db \
 *   php tools/migrate_sqlite_to_postgres.php [--dry-run]
 *
 * Idempotent : ON CONFLICT DO NOTHING — peut être relancé sans doublon.
 * Les séquences Identity sont réinitialisées sur le max(id) observé.
 */

// ─── 1. Parsing des arguments ───
$options = [
    'users' => getenv('SQLITE_USERS_DB') ?: (__DIR__ . '/../api/data/users.db'),
    'gestion' => getenv('SQLITE_GESTION_DB') ?: (__DIR__ . '/../api/data/gestion.db'),
    'host' => getenv('DB_HOST') ?: getenv('PG_HOST') ?: 'localhost',
    'port' => getenv('DB_PORT') ?: getenv('PG_PORT') ?: '5432',
    'dbname' => getenv('DB_NAME') ?: getenv('PG_NAME') ?: '',
    'user' => getenv('DB_USER') ?: getenv('PG_USER') ?: '',
    'password' => getenv('DB_PASSWORD') ?: getenv('PG_PASSWORD') ?: '',
    'sslmode' => getenv('DB_SSLMODE') ?: getenv('PG_SSLMODE') ?: '',
    'dry_run' => false,
];

foreach ($argv as $arg) {
    if ($arg === '--dry-run') { $options['dry_run'] = true; continue; }
    if (preg_match('/^--([a-z-]+)=(.*)$/', $arg, $m)) {
        $options[str_replace('-', '_', $m[1])] = $m[2];
    }
}

if ($options['dbname'] === '' || $options['user'] === '') {
    fwrite(STDERR, "ERREUR: --dbname et --user requis (ou DB_NAME / DB_USER dans l'environnement)\n");
    exit(1);
}

echo "=== Migration SQLite → PostgreSQL ===\n";
echo "Source auth    : {$options['users']}\n";
echo "Source métier  : {$options['gestion']}\n";
echo "Cible Postgres : pgsql:host={$options['host']};port={$options['port']};dbname={$options['dbname']}\n";
if ($options['dry_run']) echo "[DRY RUN] Aucune modification ne sera appliquée.\n\n";

// ─── 2. Connexion PostgreSQL (PDO) ───
$dsn = "pgsql:host={$options['host']};port={$options['port']};dbname={$options['dbname']}";
if ($options['sslmode'] !== '') $dsn .= ";sslmode={$options['sslmode']}";

try {
    $pg = new PDO($dsn, $options['user'], $options['password'], [
        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
    ]);
} catch (PDOException $e) {
    fwrite(STDERR, "ERREUR connexion Postgres: " . $e->getMessage() . "\n");
    exit(1);
}

// ─── 3. Création du schéma Postgres (réutilise api/db.php) ───
// On force DB_DRIVER=postgres AVANT d'inclure le code PHP
putenv('DB_DRIVER=postgres');
$_ENV['DB_DRIVER'] = 'postgres';
if (!defined('DB_DRIVER')) {
    // config.php définit DB_DRIVER à partir de getenv — déjà fait via putenv
}

// Charger la config (charge .env éventuel) ; forçage après incl(us) de config serait trop lourd.
// On réimplémente le schéma ici pour rester autonome de l'ordre d'inclusion :
$schema = <<<SQL
