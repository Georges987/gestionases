SQL;

if (!$options['dry_run']) {
    echo "Création du schéma PostgreSQL (si absent)...\n";
    $pg->exec($schema);
}

// ─── 4. Migration d'une table depuis SQLite → Postgres ───
function migrateTable(PDO $src, PDO $dst, string $table, array $columns, array $pkColumns, bool $dryRun) {
    $exists = $src->query("SELECT name FROM sqlite_master WHERE type='table' AND name=" . $src->quote($table))->fetchColumn();
    if (!$exists) {
        echo "  [SKIP] $table : table absente de la source SQLite\n";
        return 0;
    }
    $rows = $src->query("SELECT * FROM $table")->fetchAll(PDO::FETCH_ASSOC);
    $count = count($rows);
    if ($count === 0) {
        echo "  [OK]   $table : 0 ligne\n";
        return 0;
    }
    if ($dryRun) {
        echo "  [DRY]  $table : $count ligne(s) migrables\n";
        return $count;
    }

    $colList = implode(', ', array_map(fn($c) => '"' . $c . '"', $columns));
    $placeholders = implode(', ', array_fill(0, count($columns), '?'));
    $conflict = count($pkColumns) ? ('ON CONFLICT ("' . implode('","', $pkColumns) . '") DO NOTHING') : 'ON CONFLICT DO NOTHING';

    $stmt = $dst->prepare("INSERT INTO $table ($colList) VALUES ($placeholders) $conflict");
    $inserted = 0;
    foreach ($rows as $row) {
        $values = array_map(fn($c) => $row[$c] ?? null, $columns);
        try {
            $stmt->execute($values);
            $inserted += $stmt->rowCount();
        } catch (PDOException $e) {
            // Ignorer les doublons ; remonter les autres erreurs
            if (strpos($e->getMessage(), 'unique') === false && strpos($e->getMessage(), 'duplicate') === false) {
                fwrite(STDERR, "  [WARN] $table : " . $e->getMessage() . "\n");
            }
        }
    }
    echo "  [OK]   $table : $inserted/" . $count . " ligne(s) insérées\n";
    return $inserted;
}

// ─── 5. Migration auth (users.db) ───
echo "\n-- Base auth (users.db) --\n";
if (!file_exists($options['users'])) {
    echo "  [SKIP] users.db introuvable\n";
} else {
    $src = new PDO('sqlite:' . $options['users']);
    $src->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);
    $src->setAttribute(PDO::ATTR_DEFAULT_FETCH_MODE, PDO::FETCH_ASSOC);

    migrateTable($src, $pg, 'utilisateurs',
        ['id', 'nom', 'email', 'password_hash', 'role', 'actif', 'date_creation', 'derniere_connexion'],
        ['id'], $options['dry_run']);

    migrateTable($src, $pg, 'login_attempts',
        ['email', 'attempts', 'locked_until'],
        ['email'], $options['dry_run']);
}

// ─── 6. Migration métier (gestion.db) ───
echo "\n-- Base métier (gestion.db) --\n";
if (!file_exists($options['gestion'])) {
    echo "  [SKIP] gestion.db introuvable\n";
} else {
    $src = new PDO('sqlite:' . $options['gestion']);
    $src->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);
    $src->setAttribute(PDO::ATTR_DEFAULT_FETCH_MODE, PDO::FETCH_ASSOC);

    // Ordre compatible avec les clés étrangères
    migrateTable($src, $pg, 'membres',
        ['id', 'nom', 'prenom', 'email', 'telephone', 'role', 'statut', 'date_adhesion', 'adresse', 'photo', 'anniversaire', 'created_at', 'updated_at'],
        ['id'], $options['dry_run']);
    migrateTable($src, $pg, 'projets',
        ['id', 'titre', 'description', 'responsable', 'statut', 'date_debut', 'date_fin', 'budget', 'depenses', 'categorie', 'beneficiaires', 'localisation', 'progression', 'created_at', 'updated_at'],
        ['id'], $options['dry_run']);
    migrateTable($src, $pg, 'dons',
        ['id', 'donateur', 'email', 'montant', 'devise', 'date', 'type', 'projet_id', 'statut', 'recu', 'notes', 'created_at', 'updated_at'],
        ['id'], $options['dry_run']);
    migrateTable($src, $pg, 'transactions',
        ['id', 'libelle', 'montant', 'type', 'categorie', 'date', 'projet_id', 'validee', 'created_at', 'updated_at'],
        ['id'], $options['dry_run']);
    migrateTable($src, $pg, 'evenements',
        ['id', 'titre', 'description', 'date', 'heure', 'lieu', 'type', 'statut', 'participants', 'responsable', 'created_at', 'updated_at'],
        ['id'], $options['dry_run']);
    migrateTable($src, $pg, 'settings',
        ['key', 'value'],
        ['key'], $options['dry_run']);
    migrateTable($src, $pg, 'stock_categories',
        ['id', 'nom', 'description', 'created_at'],
        ['id'], $options['dry_run']);
    migrateTable($src, $pg, 'stock_articles',
        ['id', 'nom', 'description', 'categorie_id', 'quantite', 'seuil_alerte', 'unite', 'projet_id', 'created_at', 'updated_at'],
        ['id'], $options['dry_run']);
    migrateTable($src, $pg, 'stock_mouvements',
        ['id', 'article_id', 'type', 'quantite', 'motif', 'projet_id', 'utilisateur_id', 'date', 'created_at'],
        ['id'], $options['dry_run']);
    migrateTable($src, $pg, 'audit_logs',
        ['id', 'user_id', 'action', 'details', 'timestamp'],
        ['id'], $options['dry_run']);
    migrateTable($src, $pg, 'fournisseurs',
