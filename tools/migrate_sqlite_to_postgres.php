    id TEXT PRIMARY KEY, commande_id TEXT NOT NULL, article_id TEXT NOT NULL,
    quantite INTEGER NOT NULL, prix_unitaire DOUBLE PRECISION NOT NULL,
    FOREIGN KEY (commande_id) REFERENCES commandes_fournisseurs(id),
    FOREIGN KEY (article_id) REFERENCES stock_articles(id)
