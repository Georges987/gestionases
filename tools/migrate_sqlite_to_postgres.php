// ─── 7. Réinitialiser les séquences Identity sur le max(id) ───
if (!$options['dry_run']) {
    echo "\nRéinitialisation des séquences PostgreSQL...\n";
    $pg->exec("SELECT setval(pg_get_serial_sequence('utilisateurs', 'id'), COALESCE((SELECT max(id) FROM utilisateurs), 1), true)");
    $pg->exec("SELECT setval(pg_get_serial_sequence('audit_logs', 'id'), COALESCE((SELECT max(id) FROM audit_logs), 1), true)");
    echo "  [OK] Séquences synchronisées\n";
}

echo "\n=== Migration terminée ===\n";
if ($options['dry_run']) {
    echo "Aucun changement appliqué (--dry-run). Relancez sans --dry-run pour appliquer.\n";
} else {
    echo "Bases migrées vers PostgreSQL.\n";
    echo "Pensez à tester la connexion avant de retirer les anciennes bases SQLite.\n";
}
