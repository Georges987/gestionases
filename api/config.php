// Chargement des variables d'environnement depuis le fichier .env (fallback si getenv() ne retourne rien)
function loadEnv() {
    $envPaths = array_filter([
        getenv('APP_ENV_FILE') ?: null,                       // chemin personnalisé via env
        __DIR__ . '/.env',                                    // côté API (ancien emplacement)
        __DIR__ . '/../.env',                                 // racine du projet
    ]);
    foreach ($envPaths as $envPath) {
        if (!$envPath || !file_exists($envPath)) continue;
        $lines = file($envPath, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES);
        foreach ($lines as $line) {
            $line = trim($line);
            if ($line === '' || strpos($line, '#') === 0) continue;
            $idx = strpos($line, '=');
            if ($idx === false) continue;
            $name = trim(substr($line, 0, $idx));
            $value = trim(substr($line, $idx + 1));
            // Ne pas écraser une variable déjà définie dans l'environnement du process (Docker)
            if (getenv($name) === false) {
                putenv("{$name}={$value}");
                $_ENV[$name] = $value;
            }
        }
        return;
    }
}
loadEnv();

