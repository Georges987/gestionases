function getDBConnection() {
    if (DB_DRIVER === 'postgres') {
        return getPgConnection();
    }
    return getSqliteConnection();
}

// ─── PostgreSQL (driver par défaut, hébergement externe) ───
function getPgConnection() {
    $host = getenv('DB_HOST') ?: getenv('PG_HOST') ?: '';
    $port = getenv('DB_PORT') ?: getenv('PG_PORT') ?: '5432';
    $name = getenv('DB_NAME') ?: getenv('PG_NAME') ?: '';
    $user = getenv('DB_USER') ?: getenv('PG_USER') ?: '';
    $password = getenv('DB_PASSWORD') ?: getenv('PG_PASSWORD') ?: '';
    $sslmode = getenv('DB_SSLMODE') ?: getenv('PG_SSLMODE') ?: '';

    if ($host === '' || $name === '' || $user === '') {
        http_response_code(500);
        header('Content-Type: application/json');
        echo json_encode(['success' => false, 'error' => 'Configuration Postgres incomplète : DB_HOST, DB_NAME, DB_USER (DB_PORT, DB_PASSWORD, DB_SSLMODE optionnels)']);
        exit;
    }

    $dsn = "pgsql:host={$host};port={$port};dbname={$name}";
    if ($sslmode !== '') {
        $dsn .= ";sslmode={$sslmode}";
    }

    try {
        $pdo = new PDO($dsn, $user, $password, [
            PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
            PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
        ]);

        $pdo->exec("
            CREATE TABLE IF NOT EXISTS utilisateurs (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nom TEXT NOT NULL,
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                role TEXT NOT NULL DEFAULT 'lecteur',
                actif INTEGER DEFAULT 1,
                date_creation TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
                derniere_connexion TIMESTAMPTZ
            )
        ");
        $pdo->exec("CREATE INDEX IF NOT EXISTS idx_email ON utilisateurs(email)");
        $pdo->exec("CREATE TABLE IF NOT EXISTS login_attempts (email TEXT PRIMARY KEY, attempts INTEGER NOT NULL DEFAULT 0, locked_until TEXT)");

        // Compte admin par défaut si absent
        $stmt = $pdo->prepare("SELECT COUNT(*) FROM utilisateurs WHERE email = ?");
        $stmt->execute([ADMIN_EMAIL]);
        if ((int)$stmt->fetchColumn() === 0) {
            $hash = password_hash(ADMIN_PASSWORD, PASSWORD_DEFAULT);
            $insert = $pdo->prepare("INSERT INTO utilisateurs (nom, email, password_hash, role, actif) VALUES (?, ?, ?, 'administrateur', 1)");
            $insert->execute([ADMIN_NAME, ADMIN_EMAIL, $hash]);
        }

        return $pdo;
    } catch (PDOException $e) {
        http_response_code(500);
        header('Content-Type: application/json');
        echo json_encode(['success' => false, 'error' => 'Erreur de connexion Postgres : ' . $e->getMessage()]);
        exit;
    }
}

// ─── SQLite (fallback / développement local) ───
function getSqliteConnection() {
    // Créer le dossier data s'il n'existe pas
    $dataDir = dirname(DB_PATH);
    if (!is_dir($dataDir)) {
        mkdir($dataDir, 0750, true);
    }

    try {
        $pdo = new PDO('sqlite:' . DB_PATH);
        $pdo->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);
        $pdo->setAttribute(PDO::ATTR_DEFAULT_FETCH_MODE, PDO::FETCH_ASSOC);

        // Activer WAL pour les accès concurrents
        $pdo->exec('PRAGMA journal_mode=WAL');
        $pdo->exec('PRAGMA synchronous=NORMAL');
        $pdo->exec('PRAGMA foreign_keys=ON');

        // Créer la table si elle n'existe pas
        $pdo->exec("
            CREATE TABLE IF NOT EXISTS utilisateurs (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                nom TEXT NOT NULL,
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                role TEXT NOT NULL DEFAULT 'lecteur',
                actif INTEGER DEFAULT 1,
                date_creation DATETIME DEFAULT (datetime('now')),
                derniere_connexion DATETIME
            )
        ");

        // Créer l'index
        $pdo->exec("CREATE INDEX IF NOT EXISTS idx_email ON utilisateurs(email)");

        // Table de verrouillage des connexions (rate limiting anti brute-force)
        $pdo->exec("CREATE TABLE IF NOT EXISTS login_attempts (email TEXT PRIMARY KEY, attempts INTEGER NOT NULL DEFAULT 0, locked_until TEXT)");

        // Créer le compte admin par défaut s'il n'existe pas (identifiants configurables via .env : ADMIN_EMAIL / ADMIN_NAME / ADMIN_PASSWORD)
        $stmt = $pdo->prepare("SELECT COUNT(*) as count FROM utilisateurs WHERE email = ?");
        $stmt->execute([ADMIN_EMAIL]);
        $result = $stmt->fetch();
        if ($result['count'] == 0) {
            $hash = password_hash(ADMIN_PASSWORD, PASSWORD_DEFAULT);
            $insert = $pdo->prepare("INSERT INTO utilisateurs (nom, email, password_hash, role, actif) VALUES (?, ?, ?, 'administrateur', 1)");
            $insert->execute([ADMIN_NAME, ADMIN_EMAIL, $hash]);
        }

        return $pdo;
    } catch (PDOException $e) {
        http_response_code(500);
        header('Content-Type: application/json');
        echo json_encode(['success' => false, 'error' => 'Erreur de connexion à la base de données']);
        exit;
    }
}

function generateJWT($user) {
    $header = json_encode(['alg' => 'HS256', 'typ' => 'JWT']);
    $payload = json_encode([
        'sub' => $user['id'],
        'email' => $user['email'],
        'nom' => $user['nom'],
        'role' => $user['role'],
        'iat' => time(),
        'exp' => time() + JWT_EXPIRY,
    ]);
    
    $headerEncoded = base64UrlEncode($header);
    $payloadEncoded = base64UrlEncode($payload);
    $signature = hash_hmac('sha256', $headerEncoded . '.' . $payloadEncoded, JWT_SECRET, true);
    $signatureEncoded = base64UrlEncode($signature);
    
    return $headerEncoded . '.' . $payloadEncoded . '.' . $signatureEncoded;
}

function verifyJWT($token) {
    $parts = explode('.', $token);
    if (count($parts) !== 3) return false;
    
    $headerEncoded = $parts[0];
    $payloadEncoded = $parts[1];
    $signatureEncoded = $parts[2];
    
    $expectedSignature = hash_hmac('sha256', $headerEncoded . '.' . $payloadEncoded, JWT_SECRET, true);
    $expectedSignatureEncoded = base64UrlEncode($expectedSignature);
    
    if (!hash_equals($expectedSignatureEncoded, $signatureEncoded)) return false;
    
    $payload = json_decode(base64UrlDecode($payloadEncoded), true);
    if (!$payload) return false;
    if (isset($payload['exp']) && $payload['exp'] < time()) return false;
    
    return $payload;
}

function base64UrlEncode($data) {
    return rtrim(strtr(base64_encode($data), '+/', '-_'), '=');
}

function base64UrlDecode($data) {
    $padding = strlen($data) % 4;
    if ($padding) $data .= str_repeat('=', 4 - $padding);
    return base64_decode(strtr($data, '-_', '+/'));
}

function getAuthHeader() {
    // Priorité absolue au cookie HttpOnly (sécurité maximale pour le navigateur)
    if (!empty($_COOKIE['auth_token'])) {
        return $_COOKIE['auth_token'];
    }
    // Authorization: Bearer (clients API / curl / scripts) — légitime, contrairement au token en query string
    if (!empty($_SERVER['HTTP_AUTHORIZATION'])) {
        return str_replace('Bearer ', '', $_SERVER['HTTP_AUTHORIZATION']);
    }
    // Apache mod_php : getallheaders()
    if (function_exists('getallheaders')) {
        $headers = getallheaders();
        $headers = array_change_key_case($headers, CASE_LOWER);
        if (!empty($headers['authorization'])) {
            return str_replace('Bearer ', '', $headers['authorization']);
        }
        if (!empty($headers['x-authorization'])) {
            return str_replace('Bearer ', '', $headers['x-authorization']);
        }
    }
    // REDIRECT_HTTP_AUTHORIZATION (OVH/Apache)
    if (!empty($_SERVER['REDIRECT_HTTP_AUTHORIZATION'])) {
        return str_replace('Bearer ', '', $_SERVER['REDIRECT_HTTP_AUTHORIZATION']);
    }
    // X-Authorization via $_SERVER (fallback OVH)
    if (!empty($_SERVER['HTTP_X_AUTHORIZATION'])) {
        return str_replace('Bearer ', '', $_SERVER['HTTP_X_AUTHORIZATION']);
    }
    // NB : aucun token accepté via $_REQUEST/$_GET/$_POST — risque de fuite dans l'URL/logs
    return null;
}

function sendResponse($data, $statusCode = 200) {
    if (!headers_sent()) {
        http_response_code($statusCode);
        header('Content-Type: application/json');
        header('Access-Control-Allow-Origin: ' . ALLOWED_ORIGIN);
        header('Access-Control-Allow-Methods: GET, POST, PUT, DELETE, OPTIONS');
        header('Access-Control-Allow-Headers: Content-Type, Authorization');
    }
    echo json_encode($data);
    exit;
}
